// Build the classic browser script from the same dependency-free modules used
// by the APIs. No bundler dependency, runtime eval or extra HTTP endpoint.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const directory = path.join(root, 'lib/formula-a');
function build() {
  const names = [], chunks = [];
  for (const file of fs.readdirSync(directory).filter(x => x.endsWith('.js')).sort()) {
    const source = fs.readFileSync(path.join(directory, file), 'utf8');
    for (const m of source.matchAll(/^export (?:async )?function (\w+)/gm)) names.push(m[1]);
    const body = source.replace(/^import[^\n]+\r?\n/gm, '').replace(/^export /gm, '');
    chunks.push('// ' + file + '\n' + body.trim());
  }
  if (new Set(names).size !== names.length) throw new Error('Duplicate Formula A export');
  return '// Generated by scripts/build-formula-a.cjs. Edit lib/formula-a instead.\n' +
    '(() => {\n"use strict";\n' + chunks.join('\n\n') + '\n' +
    'globalThis.FormulaA=Object.freeze({' + names.join(',') + '});\n})();\n';
}
if (require.main === module) {
  const output = path.join(root, 'public/formula-a-modules.js');
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(output, 'utf8').replaceAll('\r\n', '\n') !== build().replaceAll('\r\n', '\n'))
      throw new Error('Formula A browser bundle is stale');
  } else fs.writeFileSync(output, build());
}
module.exports = { build };
